import assert from 'node:assert/strict';
import {generatorController, stages} from '../dealership/generator.mjs';
const requests=[], views=[], previews=[], saves=[];
const transport=async(path,body)=>{
  requests.push({path,body});
  if(path.endsWith('/start'))return {id:'job',status:'running'};
  if(path.endsWith('/save'))return {code:'GEN_NEW',name:body.name};
  if(path.endsWith('/confirm'))return {status:'running'};
  if(path.endsWith('/cancel'))return {status:'cancelled'};
  return {status:'ready',events:stages.map(stage=>({stage,state:'done',elapsed_seconds:1,decisions:{distance:.2}})),preview:'/api/generator/job/model'};
};
const panel=generatorController({transport,render:s=>views.push(structuredClone(s)),preview:p=>previews.push(p),saved:s=>saves.push(s)});
await panel.start({method:'network',seed:35,request:'a low coupe'});
await panel.poll();
assert.equal(views.at(-1).events.length,9);
assert.equal(previews[0],'/api/generator/job/model');
await panel.save('A new coupe');
assert.equal(requests.at(-1).body.name,'A new coupe');
assert.equal(saves[0].code,'GEN_NEW');
await panel.start({});await panel.confirm(true);await panel.cancel();
assert.equal(views.at(-1).status,'cancelled');
const failed=generatorController({transport:async()=>{throw Error('forced stage failure');},render:s=>views.push(s)});
await failed.start({});assert.equal(views.at(-1).message,'forced stage failure');
console.log('PASS generator controls: nine stages, preview, naming, save, confirm, cancel and failure');
let failPoll=true;
const recover=generatorController({transport:async(path,body)=>{if(path==='/api/generator/job'&&failPoll){failPoll=false;throw Error('transient poll failure');}return transport(path,body);},render:s=>views.push(s)});
await recover.resume({id:'job',status:'running',events:stages.map(stage=>({stage,state:'waiting',elapsed_seconds:0,decisions:{}}))});
await recover.poll();assert.equal(recover.state.status,'running','transport failure must leave Cancel available');
await recover.cancel();assert.equal(recover.state.status,'cancelled');
